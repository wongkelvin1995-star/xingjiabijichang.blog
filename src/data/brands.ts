/** 站内品牌数组按 editorialOrder（站长指定的展示顺序）排序：/brands、披露页、搜索默认列表、首页目录默认顺序都以它为准。 */
export const BRANDS: Brand[] = BRAND_SEEDS.map((seed) => ({ ...seed, tagline: buildTagline(seed.id) })).sort(
  (a, b) => a.editorialOrder - b.editorialOrder,
);

/**
 * 编辑顺序在 INDEXABLE_BRAND_LIMIT 以内的品牌页允许被搜索引擎收录（并写入 sitemap / IndexNow）。
 * 每个品牌都有各自的简介、价格优势、弱势、适合人群和完整价格表，不再是占位页面，所以全部放开。
 * 如果想让搜索引擎先只收录一部分（比如先收录前 10 家），把这里改成对应数字即可，
 * 超出的品牌页会自动变成 noindex，并从 sitemap 里去掉。
 */
export const INDEXABLE_BRAND_LIMIT = BRANDS.length;

export function isBrandIndexable(brand: Brand): boolean {
  return brand.editorialOrder <= INDEXABLE_BRAND_LIMIT;
}

export function getAllBrands(): Brand[] {
  return BRANDS;
}

export function getBrandBySlug(slug: string): Brand | undefined {
  return BRANDS.find((b) => b.slug === slug);
}

export function getFeaturedBrand(): Brand {
  const brand = BRANDS.find((b) => b.id === FEATURED_BRAND_ID);
  if (!brand) throw new Error(`找不到优选品牌：${FEATURED_BRAND_ID}`);
  return brand;
}

/** 品牌的显示名：有别名时写成“微风网络（Breezenet）”，用于页面标题和 meta。 */
export function displayName(brand: Brand): string {
  return brand.aliases && brand.aliases.length > 0 ? `${brand.name}（${brand.aliases[0]}）` : brand.name;
}
